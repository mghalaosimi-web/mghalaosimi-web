import assert from "node:assert/strict";
import {existsSync,readFileSync} from "node:fs";
const page=readFileSync(new URL("../app/credentials/page.tsx",import.meta.url),"utf8");
const english=readFileSync(new URL("../app/en/credentials/page.tsx",import.meta.url),"utf8");
const credentials=[...page.matchAll(/\{id:'(cisco|edraak|jsnad)-[^']+'/g)].map(x=>x[1]);
assert.equal(credentials.length,18,"The React credential archive must contain exactly 18 documented records.");
assert.equal(credentials.filter(x=>x==='cisco').length,11,"All 11 Cisco records must remain present.");
assert.equal(credentials.filter(x=>x==='edraak').length,6,"All six Edraak certificates must remain present.");
assert.equal(credentials.filter(x=>x==='jsnad').length,1,"The JSNAD credential must remain present.");
assert.equal((page.match(/verification:'https:\/\/www\.credly\.com\/badges\//g)||[]).length,11,"Every Cisco record must have its individual Credly verification URL.");
assert.equal((page.match(/'([0-9a-f]{32})'/g)||[]).length>=6,true,"Edraak verification references must be retained.");
assert.match(page,/JSNAD-ALOSEIMI-20241112/);
assert.match(page,/OpenJS Foundation · The Linux Foundation/);
assert.match(page,/function CredentialCard/);
assert.match(page,/<Image src=\{/);
assert.match(page,/loading="lazy"/);
assert.match(page,/alt=\{/);
assert.match(page,/noopener noreferrer/);
assert.match(page,/Individual reference-to-title mapping is shown only where it is confirmed/);
assert.match(page,/تعكس سجلات الشهادات المعلومات المتاحة/);
assert.match(page,/A verification link is provided only to the issuer or profile source currently recorded/);
assert.match(english,/credentials\/page/);
for(const file of [...page.matchAll(/file:'([^']+)'/g)].map(x=>x[1]))assert.ok(existsSync(new URL("../public/assets/certificates/"+file,import.meta.url)),"Missing original certificate file: "+file);
for(const file of [...page.matchAll(/preview:'([^']+)'/g)].map(x=>x[1]))assert.ok(existsSync(new URL("../public/assets/certificates/"+file,import.meta.url)),"Missing certificate preview: "+file);
assert.ok(!existsSync(new URL("../public/certificates.html",import.meta.url)));
assert.ok(!existsSync(new URL("../public/en/certificates.html",import.meta.url)));
console.log("React credential tests passed: 18 records (11 Cisco, 6 Edraak, 1 JSNAD), individual verification links, and verified local assets.");
